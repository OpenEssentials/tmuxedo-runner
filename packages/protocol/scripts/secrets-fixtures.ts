/**
 * Writes fixtures/secrets.json: fixed X25519 keys and nonces, so the sealed
 * strings are deterministic and both sides can check them (test/secrets.test.ts,
 * runner/crates/runner/tests/secrets_fixtures.rs). Keys here are test keys only.
 *
 *   node --experimental-strip-types scripts/secrets-fixtures.ts
 */
import { writeFileSync } from 'node:fs';
import { answerContext, maskContext, publicKeyOf, seal } from '../src/secrets.ts';

const runnerPrivate = Buffer.alloc(32, 7).toString('base64url');
const runnerPublic = publicKeyOf(runnerPrivate);
const fixed = (i: number) => ({ ephemeralPrivate: Buffer.alloc(32, 40 + i).toString('base64url'), nonce: Buffer.alloc(12, i).toString('base64url') });

const vectors = [
  { name: 'answer', context: answerContext('m-fixture', 's1'), plain: JSON.stringify({ values: { GH_TOKEN: 'fake-token-0123456789' }, versions: { GH_TOKEN: 3 } }) },
  { name: 'mask', context: maskContext('m-fixture'), plain: JSON.stringify({ values: ['fake-token-0123456789', 'old-fake-value-abcdef'] }) },
  { name: 'empty', context: answerContext('m-fixture', 's2'), plain: '' },
].map((v, i) => ({ ...v, ...fixed(i + 1), sealed: seal(runnerPublic, Buffer.from(v.plain), v.context, fixed(i + 1)) }));

const out = {
  note: 'Secrets (docs/protocol.md "Secrets"). Generated by scripts/secrets-fixtures.ts; checked by packages/protocol/test/secrets.test.ts and runner/crates/runner/tests/secrets_fixtures.rs. Test keys only. Change both sides or neither.',
  runnerPrivate,
  runnerPublic,
  vectors,
  wrongContext: answerContext('m-fixture', 's9'),
  frames: {
    gatewayToRunner: [
      { t: 'secret_res', id: 's1', result: { sealed: vectors[0]!.sealed, missing: [], denied: [] } },
      { t: 'secret_res', id: 's3', error: { code: 'not_allowed', message: 'GH_TOKEN is not bound to exec /usr/bin/env' } },
      { t: 'secrets', mask: vectors[1]!.sealed, policy: { names: [{ name: 'GH_TOKEN', bindings: [{ kind: 'exec', programs: ['gh'] }, { kind: 'git', hosts: ['github.com'] }] }], offlineCache: false }, revoked: ['OLD'] },
      { t: 'secrets', revoked: [] },
    ],
    runnerToGateway: [
      { t: 'secret_key', id: 'key', alg: 'x25519-hkdf-sha256-chacha20poly1305', publicKey: runnerPublic },
      { t: 'secret_req', id: 's1', names: ['GH_TOKEN'], purpose: { kind: 'exec', program: '/usr/bin/gh', paneId: 'w1:p1' } },
    ],
    invalid: [
      '{"t":"secret_res"}',
      '{"t":"secrets","revoked":"x"}',
    ],
  },
};
writeFileSync(new URL('../fixtures/secrets.json', import.meta.url), JSON.stringify(out, null, 2) + '\n');
console.log('wrote fixtures/secrets.json');
