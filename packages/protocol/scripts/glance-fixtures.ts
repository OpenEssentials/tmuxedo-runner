/**
 * Regenerate fixtures/glance.json: `npm run fixtures`.
 *
 * Each case is terminal input (what a pane printed) for a screen of
 * `cols` x `rows`, and the glance the runner must send for it. The expected
 * frames are written by hand here from the wire rules (src/glance.ts), not
 * produced by either implementation: the Rust encoder
 * (runner/crates/runner/src/glance.rs) must produce `frame` byte-for-byte as
 * JSON from `input`, and the TypeScript decoder must turn `frame` into `text`.
 */
