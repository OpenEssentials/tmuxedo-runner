#!/bin/sh
# tmuxedo runner (tmuxedo-runner) installer:
#
#   curl -fsSL https://tmuxedo.dev/dl/install.sh | sh
#
# Detects OS and architecture, downloads tmuxedo-runner from <server>/dl/,
# checks its sha256 against <server>/dl/manifest.json, installs it to
# ~/.local/bin (with `tmuxedo`, the CLI, as a symlink to it), enrols this
# machine (device code; you approve it in the browser) and installs the
# tmuxedo-holder and tmuxedo-runner user services.
#
# Upgrading an aimux-era install: the old `aimux-runner` binary becomes a
# symlink to tmuxedo-runner (as do the deprecated `aimux` CLI name), and
# install-service moves the aimux-holder/aimux-runner services over without
# ending any terminal session (the old holder keeps its sessions until it
# exits).
#
# Environment: TMUXEDO_SERVER (default https://tmuxedo.dev),
# TMUXEDO_NAME (machine name, default hostname), TMUXEDO_BIN_DIR (default
# ~/.local/bin), TMUXEDO_SKIP_ENROL=1 / TMUXEDO_SKIP_SERVICE=1 to skip those
# steps (the AIMUX_* names still work, deprecated). The same as flags
# (containers, CI, no systemd):
#
#   curl -fsSL https://tmuxedo.dev/dl/install.sh | sh -s -- --no-enrol --no-service
set -eu

SKIP_ENROL="${TMUXEDO_SKIP_ENROL:-${AIMUX_SKIP_ENROL:-0}}"
SKIP_SERVICE="${TMUXEDO_SKIP_SERVICE:-${AIMUX_SKIP_SERVICE:-0}}"
for arg in "$@"; do
  case "$arg" in
    --no-enrol | --no-enroll) SKIP_ENROL=1 ;;
    --no-service) SKIP_SERVICE=1 ;;
    -h | --help)
      printf 'usage: install.sh [--no-enrol] [--no-service]\n' >&2
      exit 0
      ;;
    *) printf 'tmuxedo: unknown option %s\n' "$arg" >&2; exit 2 ;;
  esac
done

SERVER="${TMUXEDO_SERVER:-${AIMUX_SERVER:-https://tmuxedo.dev}}"
SERVER="${SERVER%/}"
BIN_DIR="${TMUXEDO_BIN_DIR:-${AIMUX_BIN_DIR:-$HOME/.local/bin}}"
NAME="${TMUXEDO_NAME:-${AIMUX_NAME:-}}"
BIN=tmuxedo-runner

say() { printf '%s\n' "$*" >&2; }
die() { say "tmuxedo: $*"; exit 1; }

case "$(uname -s)" in
  Linux) os=linux ;;
  Darwin) os=darwin ;;
  *) die "unsupported OS $(uname -s) (Linux and macOS only)" ;;
esac
case "$(uname -m)" in
  x86_64 | amd64) arch=x86_64 ;;
  aarch64 | arm64) arch=aarch64 ;;
  *) die "unsupported architecture $(uname -m)" ;;
esac
key="$os-$arch"

if command -v curl >/dev/null 2>&1; then
  fetch() { curl -fsSL "$1" -o "$2"; }
elif command -v wget >/dev/null 2>&1; then
  fetch() { wget -q "$1" -O "$2"; }
else
  die "need curl or wget"
fi
if command -v sha256sum >/dev/null 2>&1; then
  sha() { sha256sum "$1" | cut -d' ' -f1; }
elif command -v shasum >/dev/null 2>&1; then
  sha() { shasum -a 256 "$1" | cut -d' ' -f1; }
else
  die "need sha256sum or shasum"
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT INT TERM

say "tmuxedo: downloading manifest from $SERVER/dl/"
fetch "$SERVER/dl/manifest.json" "$tmp/manifest.json" || die "cannot fetch $SERVER/dl/manifest.json"
# The manifest is generated by CI with one file entry per line:
#   "linux-x86_64": {"url": "...", "sha256": "..."},
line="$(grep "\"$key\"" "$tmp/manifest.json" | head -n 1)"
want="$(printf '%s\n' "$line" | sed -n 's/.*"sha256": *"\([0-9a-f]\{64\}\)".*/\1/p')"
[ -n "$want" ] || die "no build for $key in the manifest"
url="$(printf '%s\n' "$line" | sed -n 's/.*"url": *"\([^"]*\)".*/\1/p')"
case "$url" in
  http://* | https://*) ;;
  /*) url="$SERVER$url" ;;
  "") url="$SERVER/dl/$BIN-$key" ;;
  *) url="$SERVER/dl/$url" ;;
esac
version="$(sed -n 's/.*"version": *"\([^"]*\)".*/\1/p' "$tmp/manifest.json" | head -n 1)"

say "tmuxedo: downloading $BIN $version for $key"
fetch "$url" "$tmp/$BIN" || die "download failed"
got="$(sha "$tmp/$BIN")"
[ "$got" = "$want" ] || die "checksum mismatch (expected $want, got $got)"

mkdir -p "$BIN_DIR"
chmod 0755 "$tmp/$BIN"
mv -f "$tmp/$BIN" "$BIN_DIR/$BIN"
say "tmuxedo: installed $BIN_DIR/$BIN"
# `tmuxedo` is the CLI; `aimux-runner` and `aimux` are deprecated names kept
# so existing services, scripts and habits keep working. An aimux-era
# `aimux-runner` file is replaced by the symlink (a running process keeps
# its own copy).
ln -sfn "$BIN" "$BIN_DIR/aimux-runner"
for alias in tmuxedo aimux; do
  if [ -L "$BIN_DIR/$alias" ] || [ ! -e "$BIN_DIR/$alias" ]; then
    ln -sfn "$BIN" "$BIN_DIR/$alias"
  else
    say "tmuxedo: note: $BIN_DIR/$alias exists and is not a symlink; left as it is"
  fi
done
case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) say "tmuxedo: note: $BIN_DIR is not on your PATH" ;;
esac

"$BIN_DIR/$BIN" version >&2 || die "the installed binary does not run"

if [ "$SKIP_ENROL" = 1 ]; then
  say "tmuxedo: skipped enrolment (run: $BIN enrol --server $SERVER)"
elif [ -n "$NAME" ]; then
  "$BIN_DIR/$BIN" enrol --server "$SERVER" --name "$NAME" </dev/null
else
  "$BIN_DIR/$BIN" enrol --server "$SERVER" </dev/null
fi

if [ "$SKIP_SERVICE" = 1 ]; then
  say "tmuxedo: skipped the service install (run: $BIN install-service)"
else
  "$BIN_DIR/$BIN" install-service
fi
say "tmuxedo: done. This machine appears in tmuxedo once the runner connects."
